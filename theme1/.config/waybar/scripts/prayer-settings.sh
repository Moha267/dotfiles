#!/bin/bash

# Prayer Times Settings Dialog
# Requires: yad (sudo pacman -S yad)

CONFIG_FILE="$HOME/.config/waybar/scripts/prayer.conf"

# Load current config
if [[ -f "$CONFIG_FILE" ]]; then
    source "$CONFIG_FILE"
else
    LATITUDE=31.0364
    LONGITUDE=31.3807
    METHOD=5
fi

# Method list for dropdown (value!label format for yad)
METHOD_LIST=(
    "1!Karachi — University of Islamic Sciences"
    "2!ISNA — Islamic Society of North America"
    "3!Muslim World League"
    "4!Umm Al-Qura University, Makkah"
    "5!Egyptian General Authority of Survey"
    "7!Tehran — Institute of Geophysics"
    "8!Gulf Region"
    "9!Kuwait"
    "10!Qatar"
    "11!Singapore — Majlis Ugama Islam"
    "12!France — Union Organization Islamique"
    "13!Turkey — Diyanet İşleri Başkanlığı"
    "14!Russia — Spiritual Administration of Muslims"
    "15!Moonsighting Committee Worldwide"
)

# Build the combo list string with current method first
COMBO="${METHOD}"
for ENTRY in "${METHOD_LIST[@]}"; do
    KEY="${ENTRY%%!*}"
    LABEL="${ENTRY##*!}"
    [[ "$KEY" != "$METHOD" ]] && COMBO+="|${KEY} — ${LABEL}" || COMBO+="|${KEY} — ${LABEL}"
done

# Find the current method label to pre-select it
CURRENT_LABEL=""
for ENTRY in "${METHOD_LIST[@]}"; do
    KEY="${ENTRY%%!*}"
    LABEL="${ENTRY##*!}"
    if [[ "$KEY" == "$METHOD" ]]; then
        CURRENT_LABEL="${KEY} — ${LABEL}"
        break
    fi
done

# Build combo with current selection first
COMBO_STR="$CURRENT_LABEL"
for ENTRY in "${METHOD_LIST[@]}"; do
    KEY="${ENTRY%%!*}"
    LABEL="${ENTRY##*!}"
    [[ "${KEY} — ${LABEL}" != "$CURRENT_LABEL" ]] && COMBO_STR+="|${KEY} — ${LABEL}"
done

# Show the dialog
RESULT=$(yad \
    --title="🕌 Prayer Times Settings" \
    --form \
    --width=450 \
    --separator="|" \
    --button="Save:0" \
    --button="Cancel:1" \
    --field="Latitude:NUM"  "${LATITUDE}!-90..90!0.0001!4" \
    --field="Longitude:NUM" "${LONGITUDE}!-180..180!0.0001!4" \
    --field="Calculation Method:CB" "$COMBO_STR" \
    2>/dev/null)

# Exit if cancelled
[[ $? -ne 0 ]] && exit 0

# Parse results
NEW_LAT=$(echo "$RESULT"  | cut -d'|' -f1)
NEW_LON=$(echo "$RESULT"  | cut -d'|' -f2)
METHOD_STR=$(echo "$RESULT" | cut -d'|' -f3)
NEW_METHOD=$(echo "$METHOD_STR" | cut -d' ' -f1)

# Validate
if [[ -z "$NEW_LAT" || -z "$NEW_LON" || -z "$NEW_METHOD" ]]; then
    yad --error --text="Invalid input. Settings not saved." 2>/dev/null
    exit 1
fi

# Save config
cat > "$CONFIG_FILE" <<EOF
# Prayer Times Widget Configuration
# Generated by prayer-settings.sh on $(date)

LATITUDE=${NEW_LAT}
LONGITUDE=${NEW_LON}
METHOD=${NEW_METHOD}

# Available Methods:
# 1  - University of Islamic Sciences, Karachi
# 2  - Islamic Society of North America (ISNA)
# 3  - Muslim World League
# 4  - Umm Al-Qura University, Makkah
# 5  - Egyptian General Authority of Survey
# 7  - Institute of Geophysics, University of Tehran
# 8  - Gulf Region
# 9  - Kuwait
# 10 - Qatar
# 11 - Majlis Ugama Islam Singapura (Singapore)
# 12 - Union Organization Islamic de France
# 13 - Diyanet İşleri Başkanlığı, Turkey
# 14 - Spiritual Administration of Muslims of Russia
# 15 - Moonsighting Committee Worldwide
EOF

# Clear cache so new settings take effect immediately
rm -f /tmp/waybar_prayer_*.json

# Restart Waybar
pkill waybar
waybar &disown

yad --info --text="✅ Settings saved!\nLat: ${NEW_LAT} | Lon: ${NEW_LON} | Method: ${NEW_METHOD}" \
    --timeout=3 --no-buttons 2>/dev/null
